<script setup>
import { useSeoMeta } from '@unhead/vue';

useSeoMeta({
  "title": "Landowner Joint Ventures & Partnerships | Al-Noor Properties BD",
  "description": "Partner with Al-Noor Properties to transform your prime land in Dhaka into iconic luxury residential landmarks.",
  "ogTitle": "Landowner Joint Ventures | Al-Noor Properties BD",
