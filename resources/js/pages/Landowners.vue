  "ogImage": "/images/logo.jpeg"
});

import { reactive, ref } from 'vue';
import axios from 'axios';
import confetti from 'canvas-confetti';

const loading = ref(false);
const submitted = ref(false);

const form = reactive({
  name: '',
  phone: '',
  email: '',
  landSize: '',
  landLocation: '',
  message: ''
});

const submitLandForm = async () => {
  loading.value = true;
  try {
    await axios.post('/api/inquiries', {
      name: form.name,
      email: form.email,
      phone: form.phone,
      source: 'landowner',
      subject: `Land Joint Venture: ${form.landSize} at ${form.landLocation}`,
      message: `Land Size: ${form.landSize}\nLocation: ${form.landLocation}\nNotes: ${form.message}`
    });

    submitted.value = true;
    confetti({
      particleCount: 50,
      spread: 60,
      origin: { y: 0.6 },
      colors: ['#d4a751', '#e2c07a', '#c6923b']
    });
  } catch (err) {
    console.error('Error submitting landowner form', err);
    submitted.value = true;
  } finally {
    loading.value = false;
  }
};
</script>
